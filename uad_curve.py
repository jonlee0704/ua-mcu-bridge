def tapered_to_db(tapered: float) -> float:
    """Calculate exact Apollo Console fader dB (-144.0 to +12.0) from tapered position (0.0 to 1.0).
    Accuracy is within 0.05 dB across the entire fader throw.
    """
    t = max(0.0, min(1.0, float(tapered)))
    if t <= 0.0001:
        return -144.0
    if t >= 1.0:
        return 12.0
    
    # 201-point uniform grid with step 0.005
    idx = int(t / 0.005)
    if idx >= len(CALIBRATED_FADER_TABLE) - 1:
        return 12.0
    
    t0, db0 = CALIBRATED_FADER_TABLE[idx]
    t1, db1 = CALIBRATED_FADER_TABLE[idx + 1]
    ratio = (t - t0) / (t1 - t0)
    return db0 + ratio * (db1 - db0)


def db_to_tapered(db: float) -> float:
    """Calculate exact tapered fader position (0.0 to 1.0) from decibels (-144.0 to +12.0)."""
    val = float(db)
    if val <= -144.0:
        return 0.0
    if val >= 12.0:
        return 1.0
    
    for i in range(len(CALIBRATED_FADER_TABLE) - 1):
        t0, db0 = CALIBRATED_FADER_TABLE[i]
        t1, db1 = CALIBRATED_FADER_TABLE[i + 1]
        if db0 <= val <= db1:
            ratio = (val - db0) / (db1 - db0)
            return t0 + ratio * (t1 - t0)
    return 1.0


def format_db_7char(db: float) -> str:
    """Format Apollo Console fader dB into exact 7-char string for SSL UF8 scribble strip.
    Centered directly under the channel name text.
    Accurately reflects Apollo Console GUI scale: +12, +6, 0, -6, -12, -20, -32, -56 down to -oo.
    """
    if db <= -140.0:
        return " -oo dB"
    if abs(db) < 0.05:
        return " 0.0dB "
    if db > 0:
        s = f"+{db:.1f}dB" if db < 10.0 else f"+{db:.0f}dB"
        return f"{s:^7}"[:7]
    if db <= -99.95:
        s = f"{round(db):.0f}dB"
        return f" {s}"[:7] if len(s) == 6 else f"{s:^7}"[:7]
    if db > -10.0:
        return f" {db:.1f}dB"
    return f"{db:.1f}dB"

